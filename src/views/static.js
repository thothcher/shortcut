import { config } from '../config.js';
import { html } from '../lib/html.js';
import { formatMoney } from '../lib/format.js';
import { page } from './layout.js';
import { icon } from './icons.js';

const co = config.company;
const isTemplate = !process.env.COMPANY_NAME;

function legal(c, { title, updated = '2026 წლის 29 ოქტომბერი', sections }) {
  return page(c, {
    title,
    body: html`<article class="container narrow prose">
      <h1>${title}</h1>
      <p class="muted small">ბოლო განახლება: ${updated}</p>
      ${isTemplate &&
      html`<p class="alert alert--warn">${icon('alert')}<span>ეს ტექსტი შაბლონია. გაშვებამდე შეავსე კომპანიის მონაცემები (.env ფაილში COMPANY_*) და გადაახედე იურისტს.</span></p>`}
      ${sections.map(([h, items]) => html`<section><h2>${h}</h2>${items.map((p) => html`<p>${p}</p>`)}</section>`)}
    </article>`,
  });
}

