/** Generic message page for 403 / 404 / 500 and similar. */
export function messagePage(c, { title, text, iconName = 'alert', action }) {
  return page(c, {
    title,
    body: html`<section class="container narrow status-page">
      <span class="status-icon">${icon(iconName, 40)}</span>
      <h1>${title}</h1>
      ${text && html`<p class="lead">${text}</p>`}
      ${action ?? html`<a class="btn btn--primary" href="${c.user ? '/library' : '/'}">${c.user ? 'ბიბლიოთეკაში დაბრუნება' : 'მთავარზე დაბრუნება'}</a>`}
    </section>`,
  });
}
